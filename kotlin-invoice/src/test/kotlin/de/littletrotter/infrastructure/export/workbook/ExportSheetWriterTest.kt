package de.littletrotter.infrastructure.export.workbook

import de.littletrotter.shared.GermanTime
import org.apache.poi.ss.usermodel.FillPatternType
import org.apache.poi.xssf.usermodel.XSSFCellStyle
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import java.time.OffsetDateTime
import java.time.ZoneOffset

/**
 * the "Export" cover sheet: title (A1, the product line), subtitle (A2), the "Export"
 * section (unchanged key/value rows and per-sheet record counts), the "Hinweise zum Export"
 * section and the "Datenschutz (DSGVO)" section, then the closing line — in that fixed row order.
 */
class ExportSheetWriterTest {

    private val notes = (1..SIX_NOTES).map { n -> ExportSheetNote(label = "Note$n", text = "Note $n explanatory text") }
    private val privacyParagraphs = (1..SEVEN_PARAGRAPHS).map { n -> ExportSheetPrivacyParagraph(article = "Art. $n", text = "Paragraph $n text") }

    private val labels = ExportSheetLabels(
        subtitlePattern = "Selection: {0}",
        exportSectionLabel = "Export",
        keyValue = ExportSheetKeyValueLabels(
            fieldColumnHeader = "Field",
            valueColumnHeader = "Value",
            generatedAtLabel = "Generated at",
            actingUserLabel = "Generated by",
            selectionLabel = "Selection",
            applicationVersionLabel = "Application version",
            recordCountLabelPattern = "Records: %s",
        ),
        notes = ExportSheetNotesLabels(sectionLabel = "Notes", notes = notes),
        privacy = ExportSheetPrivacyLabels(sectionLabel = "Privacy", paragraphs = privacyParagraphs),
        closingLabel = "This is general guidance, not legal advice.",
    )

    private fun metadata(generatedAt: OffsetDateTime = OffsetDateTime.now(), appliedSelection: String = "none") = ExportMetadata(
        productLine = "Little Trotter Haflinger (0.7.0-SNAPSHOT)",
        generatedAt = generatedAt,
        actingUser = "erika.musterfrau",
        appliedSelection = appliedSelection,
        applicationVersion = "0.7.0-SNAPSHOT",
    )

    @Test
    fun `Export sheet is written first, with the title row and subtitle ahead of the Export section`() {
        val generatedAt = OffsetDateTime.of(2026, 9, 7, 10, 30, 0, 0, ZoneOffset.UTC)
        val bytes = writeWorkbook { writer ->
            val invoices = writer.sheet("Invoices")
            invoices.header(listOf("Id"), listOf(8))
            invoices.row().text("R-1")
            invoices.row().text("R-2")

            val positions = writer.sheet("Positions")
            positions.header(listOf("Id"), listOf(8))
            positions.row().text("P-1")

            ExportSheetWriter.write(
                writer = writer,
                labels = labels,
                metadata = metadata(generatedAt, "Period 2026-01-01 to 2026-09-07"),
                summaries = listOf(
                    ExportSheetSummary("Invoices", invoices.recordCount),
                    ExportSheetSummary("Positions", positions.recordCount),
                ),
            )
        }

        readWorkbook(bytes).use { wb ->
            assertThat(wb.getSheetName(0)).isEqualTo("Export")
            assertThat(wb.numberOfSheets).isEqualTo(3)

            val sheet = wb.getSheetAt(0)
            assertThat(sheet.getRow(0).getCell(0).stringCellValue).isEqualTo("Little Trotter Haflinger (0.7.0-SNAPSHOT)")
            assertThat(sheet.getRow(1).getCell(0).stringCellValue).isEqualTo("Selection: Period 2026-01-01 to 2026-09-07")
            // Row 2 is a blank spacer — an empty row with no cells at all, not a blank-typed cell.
            assertThat(sheet.getRow(2).getCell(0)).isNull()
            assertThat(sheet.getRow(3).getCell(0).stringCellValue).isEqualTo("Export")
            assertThat(sheet.getRow(4).getCell(0).stringCellValue).isEqualTo("Field")
            assertThat(sheet.getRow(4).getCell(1).stringCellValue).isEqualTo("Value")
        }
    }

    @Test
    fun `title row uses the title style - 14 bold, no fill`() {
        val bytes = writeWorkbook { writer -> ExportSheetWriter.write(writer, labels, metadata(), emptyList()) }
        readWorkbook(bytes).use { wb ->
            val style = wb.getSheetAt(0).getRow(0).getCell(0).cellStyle as XSSFCellStyle
            assertThat(style.font.fontHeightInPoints.toInt()).isEqualTo(14)
            assertThat(style.font.bold).isTrue()
            assertThat(style.fillPattern).isEqualTo(FillPatternType.NO_FILL)
        }
    }

    @Test
    fun `section headings use the section style - 14 bold on the section fill`() {
        val bytes = writeWorkbook { writer -> ExportSheetWriter.write(writer, labels, metadata(), emptyList()) }
        readWorkbook(bytes).use { wb ->
            val sheet = wb.getSheetAt(0)
            val exportSectionStyle = sheet.getRow(EXPORT_SECTION_ROW).getCell(0).cellStyle as XSSFCellStyle
            assertThat(exportSectionStyle.font.fontHeightInPoints.toInt()).isEqualTo(14)
            assertThat(exportSectionStyle.font.bold).isTrue()
            assertThat(exportSectionStyle.fillPattern).isEqualTo(FillPatternType.SOLID_FOREGROUND)
            assertThat(exportSectionStyle.fillForegroundXSSFColor.argbHex).isEqualTo("FFE8F0FE")
        }
    }

    @Test
    fun `the Field-Value sub-header uses the same look as every sheet's own column header`() {
        val bytes = writeWorkbook { writer -> ExportSheetWriter.write(writer, labels, metadata(), emptyList()) }
        readWorkbook(bytes).use { wb ->
            val style = wb.getSheetAt(0).getRow(FIELD_VALUE_HEADER_ROW).getCell(0).cellStyle as XSSFCellStyle
            assertThat(style.font.fontHeightInPoints.toInt()).isEqualTo(14)
            assertThat(style.font.bold).isTrue()
            assertThat(style.font.getXSSFColor().argbHex).isEqualTo("FFFFFFFF")
            assertThat(style.fillForegroundXSSFColor.argbHex).isEqualTo("FF1967D2")
        }
    }

    @Test
    fun `existing Export section key-value rows and record counts sit right after the sub-header, unchanged`() {
        val generatedAt = OffsetDateTime.of(2026, 9, 7, 10, 30, 0, 0, ZoneOffset.UTC)
        val bytes = writeWorkbook { writer ->
            val invoices = writer.sheet("Invoices")
            invoices.header(listOf("Id"), listOf(8))
            invoices.row().text("R-1")
            invoices.row().text("R-2")
            val positions = writer.sheet("Positions")
            positions.header(listOf("Id"), listOf(8))
            positions.row().text("P-1")

            ExportSheetWriter.write(
                writer, labels, metadata(generatedAt, "Period 2026-01-01 to 2026-09-07"),
                listOf(ExportSheetSummary("Invoices", invoices.recordCount), ExportSheetSummary("Positions", positions.recordCount)),
            )
        }

        readWorkbook(bytes).use { wb ->
            val sheet = wb.getSheetAt(0)
            assertThat(sheet.getRow(GENERATED_AT_ROW).getCell(0).stringCellValue).isEqualTo("Generated at")
            val expectedLocal = generatedAt.atZoneSameInstant(GermanTime.ZONE).toLocalDateTime()
            assertThat(sheet.getRow(GENERATED_AT_ROW).getCell(1).localDateTimeCellValue).isEqualTo(expectedLocal)

            assertThat(sheet.getRow(GENERATED_AT_ROW + 1).getCell(0).stringCellValue).isEqualTo("Generated by")
            assertThat(sheet.getRow(GENERATED_AT_ROW + 1).getCell(1).stringCellValue).isEqualTo("erika.musterfrau")

            assertThat(sheet.getRow(GENERATED_AT_ROW + 2).getCell(0).stringCellValue).isEqualTo("Selection")
            assertThat(sheet.getRow(GENERATED_AT_ROW + 2).getCell(1).stringCellValue).isEqualTo("Period 2026-01-01 to 2026-09-07")

            assertThat(sheet.getRow(GENERATED_AT_ROW + 3).getCell(0).stringCellValue).isEqualTo("Application version")
            assertThat(sheet.getRow(GENERATED_AT_ROW + 3).getCell(1).stringCellValue).isEqualTo("0.7.0-SNAPSHOT")

            assertThat(sheet.getRow(GENERATED_AT_ROW + 4).getCell(0).stringCellValue).isEqualTo("Records: Invoices")
            assertThat(sheet.getRow(GENERATED_AT_ROW + 4).getCell(1).numericCellValue).isEqualTo(2.0)
            assertThat(sheet.getRow(GENERATED_AT_ROW + 5).getCell(0).stringCellValue).isEqualTo("Records: Positions")
            assertThat(sheet.getRow(GENERATED_AT_ROW + 5).getCell(1).numericCellValue).isEqualTo(1.0)
        }
    }

    @Test
    fun `notes and privacy sections follow, in order, with B cells wrapped in the secondary style`() {
        val summaryCount = 1
        val bytes = writeWorkbook { writer ->
            ExportSheetWriter.write(
                writer, labels, metadata(),
                listOf(ExportSheetSummary("Invoices", 2L)),
            )
        }
        readWorkbook(bytes).use { wb ->
            val sheet = wb.getSheetAt(0)
            // generatedAt, actingUser, selection, applicationVersion (4 rows), then the summary
            // rows, then one spacer row, then the "Notes" section heading itself.
            val notesSectionRow = GENERATED_AT_ROW + FIXED_KEY_VALUE_ROWS + summaryCount + 1
            assertThat(sheet.getRow(notesSectionRow).getCell(0).stringCellValue).isEqualTo("Notes")

            val firstNoteRow = notesSectionRow + 1
            notes.forEachIndexed { index, note ->
                val row = sheet.getRow(firstNoteRow + index)
                assertThat(row.getCell(0).stringCellValue).isEqualTo(note.label)
                assertThat(row.getCell(1).stringCellValue).isEqualTo(note.text)
                val bStyle = row.getCell(1).cellStyle as XSSFCellStyle
                assertThat(bStyle.wrapText).isTrue()
                assertThat(bStyle.font.getXSSFColor().argbHex).isEqualTo("FF5F6368")
            }

            val privacySectionRow = firstNoteRow + notes.size + 1 // spacer between notes and privacy
            assertThat(sheet.getRow(privacySectionRow).getCell(0).stringCellValue).isEqualTo("Privacy")

            val firstPrivacyRow = privacySectionRow + 1
            privacyParagraphs.forEachIndexed { index, paragraph ->
                val row = sheet.getRow(firstPrivacyRow + index)
                assertThat(row.getCell(0).stringCellValue).isEqualTo(paragraph.article)
                assertThat(row.getCell(1).stringCellValue).isEqualTo(paragraph.text)
                val bStyle = row.getCell(1).cellStyle as XSSFCellStyle
                assertThat(bStyle.wrapText).isTrue()
            }

            val closingRow = firstPrivacyRow + privacyParagraphs.size + 1 // spacer between privacy and closing
            assertThat(sheet.getRow(closingRow).getCell(0).stringCellValue).isEqualTo(labels.closingLabel)
        }
    }

    @Test
    fun `an empty summaries list still writes the fixed metadata rows and every section afterwards`() {
        val bytes = writeWorkbook { writer -> ExportSheetWriter.write(writer, labels, metadata(), emptyList()) }
        readWorkbook(bytes).use { wb ->
            val sheet = wb.getSheetAt(0)
            assertThat(sheet.getRow(GENERATED_AT_ROW + 3).getCell(0).stringCellValue).isEqualTo("Application version")
            // No summary rows: the notes section heading sits right after one spacer row (an
            // empty row with no cells at all, not a blank-typed cell).
            assertThat(sheet.getRow(GENERATED_AT_ROW + 4).getCell(0)).isNull()
            assertThat(sheet.getRow(GENERATED_AT_ROW + 5).getCell(0).stringCellValue).isEqualTo("Notes")
        }
    }

    @Test
    fun `mode B's own note text - only two data sheets - is whatever the caller supplied, unchanged by this writer`() {
        val modeBNotes = listOf(ExportSheetNote("Contents", "Invoices and Positions only")) +
            notes.drop(1)
        val bytes = writeWorkbook { writer ->
            ExportSheetWriter.write(writer, labels.copy(notes = labels.notes.copy(notes = modeBNotes)), metadata(), emptyList())
        }
        readWorkbook(bytes).use { wb ->
            val sheet = wb.getSheetAt(0)
            val noSummaries = 0
            val notesSectionRow = GENERATED_AT_ROW + FIXED_KEY_VALUE_ROWS + noSummaries + 1
            assertThat(sheet.getRow(notesSectionRow + 1).getCell(1).stringCellValue).isEqualTo("Invoices and Positions only")
        }
    }

    @Test
    fun `column widths are the Export sheet's own fixed A-40 B-110, and there is no autofilter or freeze pane`() {
        val bytes = writeWorkbook { writer -> ExportSheetWriter.write(writer, labels, metadata(), emptyList()) }
        readWorkbook(bytes).use { wb ->
            val sheet = wb.getSheetAt(0)
            assertThat(sheet.getColumnWidth(0)).isEqualTo(ColumnWidths.EXPORT_FIELD * CHARACTER_WIDTH_UNITS)
            assertThat(sheet.getColumnWidth(1)).isEqualTo(ColumnWidths.EXPORT_VALUE * CHARACTER_WIDTH_UNITS)
            assertThat(sheet.paneInformation).isNull()
        }
    }

    private companion object {
        const val SIX_NOTES = 6
        const val SEVEN_PARAGRAPHS = 7
        const val CHARACTER_WIDTH_UNITS = 256

        // Fixed row layout: title(0), subtitle(1), spacer(2), "Export" section(3), sub-header(4),
        // then the key/value rows starting at GENERATED_AT_ROW.
        const val EXPORT_SECTION_ROW = 3
        const val FIELD_VALUE_HEADER_ROW = 4
        const val GENERATED_AT_ROW = 5

        /** Rows after "Generated at" up to and including "Application version" (3), plus one to
         *  convert the last such row index into "how many rows to skip" — see the row-layout
         *  comment on each test that uses it. */
        const val FIXED_KEY_VALUE_ROWS = 4
    }
}
